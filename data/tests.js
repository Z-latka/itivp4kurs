const publicTest = (test, withQuestions = false) => {
  const { questions, levels, crisisQuestion, ...meta } = test;
  const result = { ...meta, questionsCount: questions.length };
  if (withQuestions) {
    result.questions = questions.map((text, index) => ({ id: index, text }));
  }
  return result;
};

const findTest = (id) => TESTS.find((t) => t.id === id);

// Подсчёт результата: answers — массив значений по порядку вопросов
const scoreTest = (test, answers) => {
  if (!Array.isArray(answers) || answers.length !== test.questions.length) {
    return { error: `Нужно ответить на все ${test.questions.length} вопросов` };
  }
  const allowed = test.options.map((o) => o.value);
  if (!answers.every((a) => allowed.includes(Number(a)))) {
    return { error: "Недопустимое значение ответа" };
  }
  const values = answers.map(Number);
  const score = values.reduce((sum, v) => sum + v, 0);
  const maxScore = test.questions.length * Math.max(...allowed);
  const level = test.levels.find((l) => score <= l.max) || test.levels.at(-1);
  const crisis =
    test.crisisQuestion !== undefined && values[test.crisisQuestion] > 0;
  return { score, maxScore, level, crisis, answers: values };
};

module.exports = { TESTS, publicTest, findTest, scoreTest };
